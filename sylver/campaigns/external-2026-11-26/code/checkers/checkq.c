/* checkq v3: independent checker for a "P-set certificate" (Sylver worker, 2026-10-19). Shares no code with fin3/even3/pattern2.
   Usage: checkq JOURNAL g1 g2 ... gk     (the root position is given on the command line; the journal header must name the same root)
   Env: ENDERLOG=file appends the 15-byte key (+1 pad byte) of every ender child used. ENDER=1 allows the ender theorem as a leaf (counted; a run with enders=0 at the end does not depend on it),
        CKPT=file checkpoint/resume (every CKSTEP keys, default 1,000,000), START/END optional key-index range (testing).
   Journal = fin3 P-journal: 64-byte header "fin3 [g1, g2, ...] M=m" + 16-byte records (15-byte Kunz key mod M, 1 check byte ignored).
   SYLVER COINAGE: a position is the numerical semigroup S generated by the numbers named so far; a legal move is any gap a of S (a not in S);
   naming 1 loses at once, so 1 is never a winning move and a position whose only gap is 1 is P (the mover must name 1).
   Roots must have gcd 1 (finite game: every position containing the root has finitely many gaps, all <= F(root)).
   CLAIM CHECKED: every X in Q is P. For each X in Q: X is the Apery set mod M of a numerical semigroup containing the root; if X's only gap
   is 1, X is P (terminal). Otherwise for every gap a>=2 of X, Y=X+a must have a gap other than 1 (else Y is the terminal P and X is N:
   FAIL) and must have a reply y>=2 with Y+y in Q or Y+y terminal (or, ENDER=1, Y an ender). Induction on the number of gaps: every child
   of X is N, the move 1 loses, so X is P. Finally the root is in Q. */
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <stdint.h>
#include <time.h>
#define L 2048
typedef struct { unsigned char k[15]; } Key;
static int M; static int root[64], nroot;
static Key *tab; static uint64_t tmask; static unsigned char *used;
static void die(const char*m){ printf("ERROR %s\n",m); exit(2); }
static uint64_t hk(const Key *k){ uint64_t h=1469598103934665603ULL; for(int i=0;i<15;i++){ h^=k->k[i]; h*=1099511628211ULL; } h^=h>>31; return h; }
static int tfind(const Key *k){ uint64_t i=hk(k)&tmask; while(used[i]){ if(!memcmp(tab[i].k,k->k,15)) return 1; i=(i+1)&tmask; } return 0; }
static int tins(const Key *k){ uint64_t i=hk(k)&tmask; while(used[i]){ if(!memcmp(tab[i].k,k->k,15)) return 0; i=(i+1)&tmask; } used[i]=1; tab[i]=*k; return 1; }
static int gcd(int a,int b){ while(b){int t=a%b;a=b;b=t;} return a; }
/* in[n]=1 iff n in S, for 0<=n<L; S always contains every n > F (F < L-M is asserted for the root, hence for every X containing it) */
static int frob(const unsigned char *in){ for(int n=L-1;n>0;n--) if(!in[n]) return n; return 0; }
/* S' = S + aN (adjoin a); t = F(S); returns F(S'). n in S' iff n in S or n-a in S' (ascending n). Nothing above t changes. */
static int adjoin(const unsigned char *in, int t, int a, unsigned char *out){ memcpy(out,in,L); if(out[a]) return t;
  for(int n=a;n<=t;n++){ if(out[n-a]) out[n]=1; }
  while(t>0 && out[t]) t--;
  return t; }
/* Kunz key mod M: k[r-1] = (w_r - r)/M, w_r = least element of S that is = r mod M */
static void tokey(const unsigned char *in, Key *k){ memset(k,0,sizeof *k); for(int r=1;r<M;r++){ int w=r; while(w<L && !in[w]) w+=M;
    if(w>=L) die("Apery element beyond L"); int q=(w-r)/M; if(q>=240) die("coordinate overflow"); k->k[r-1]=q; }
  if(M<16) k->k[14]=0xF0+M; }
/* key -> membership; 0 if not the Apery set of a numerical semigroup containing M and the root */
static int fromkey(const Key *k, unsigned char *in){ int w[16]; w[0]=0; if(M<16 && k->k[14]!=0xF0+M) return 0;
  for(int r=1;r<M;r++){ w[r]=r+M*k->k[r-1]; if(w[r]>=L) return 0; }
  for(int i=1;i<M;i++) for(int j=1;j<M;j++) if(w[i]+w[j] < w[(i+j)%M]) return 0;   /* Kunz/Apery closure: S = union of w_r + MN is closed under + */
  for(int n=0;n<L;n++) in[n]= n>=w[n%M];
  for(int i=0;i<nroot;i++) if(!in[root[i]]) return 0;                              /* contains every root generator, so contains the root */
  return 1; }
/* ender (Hutchings; Sicherman Integers 2 (2002) G02 §1/§3): t>1 and no two gaps a<b with a+b=t */
static int is_ender(const unsigned char *in){ int t=frob(in); if(t<=1) return 0; for(int a=1;2*a<t;a++) if(!in[a]&&!in[t-a]) return 0; return 1; }
int main(int argc,char**argv){ if(argc<3){fprintf(stderr,"usage: checkq journal.bin g1 g2 ...\n");return 2;}
  int use_ender=getenv("ENDER")&&atoi(getenv("ENDER"))==1;
  nroot=0; for(int i=2;i<argc;i++){ if(nroot>=64) die("too many generators"); root[nroot]=atoi(argv[i]); if(root[nroot]<2||root[nroot]>=L) die("bad generator"); nroot++; }
  int g=0,mn=L; for(int i=0;i<nroot;i++){ g=gcd(g,root[i]); if(root[i]<mn) mn=root[i]; }
  if(g!=1) die("root gcd > 1: unbounded game, not a finite certificate");
  M=mn; if(M>16) die("smallest generator > 16 (Kunz key has 15 coordinates)");
  FILE*f=fopen(argv[1],"rb"); if(!f) die("cannot open journal");
  char hdr[65]={0}; if(fread(hdr,1,64,f)!=64) die("short header");
  { char want[300]; int n=sprintf(want,"fin3 ["); for(int i=0;i<nroot;i++) n+=sprintf(want+n,"%s%d",i?", ":"",root[i]); sprintf(want+n,"] M=%d",M);
    if(strncmp(hdr,want,63)!=0) die("journal header does not name this root/M"); }
  static unsigned char rin[L], X[L], Y[L], Z[L]; memset(rin,0,L); rin[0]=1;
  for(int n=1;n<L;n++) for(int i=0;i<nroot;i++) if(n>=root[i]&&rin[n-root[i]]){rin[n]=1;break;}
  int F=frob(rin); if(F+M>=L) die("root Frobenius too large for L");
  fseek(f,0,SEEK_END); long sz=ftell(f); long nrec=(sz-64)/16; fseek(f,64,SEEK_SET);
  int bits=4; while((1ULL<<bits) < (uint64_t)nrec*2+16) bits++; tmask=(1ULL<<bits)-1;
  tab=malloc(sizeof(Key)<<bits); used=calloc(1ULL<<bits,1); Key *list=malloc(sizeof(Key)*(nrec+1)); if(!tab||!used||!list) die("out of memory");
  long nq=0, dup=0; unsigned char rec[16];
  for(long i=0;i<nrec;i++){ if(fread(rec,1,16,f)!=16) break; Key k; memcpy(k.k,rec,15); if(tins(&k)) list[nq++]=k; else dup++; }
  fclose(f);
  Key rk; tokey(rin,&rk); if(!tfind(&rk)){ printf("FAIL root not in Q\n"); return 1; }
  long children=0, probes=0, enders=0, termw=0, start=0, end=nq; const char *ck=getenv("CKPT"); long ckstep=getenv("CKSTEP")?atol(getenv("CKSTEP")):1000000;
  if(getenv("START")) start=atol(getenv("START")); if(getenv("END")) end=atol(getenv("END")); if(end>nq) end=nq; long rstart=start; /* rstart: requested start (resume does not make a run partial) */
  if(ck){ FILE*c=fopen(ck,"r"); if(c){ long jsz,jnq,ii,ch,pr,tw,en; if(fscanf(c,"%ld %ld %ld %ld %ld %ld %ld",&jsz,&jnq,&ii,&ch,&pr,&tw,&en)==7){
        if(jsz!=sz||jnq!=nq) die("checkpoint is for a different journal"); if(rstart!=0) die("START with CKPT");
        start=ii; children=ch; probes=pr; termw=tw; enders=en; fprintf(stderr,"[checkq] resume at key %ld/%ld\n",start,nq); } fclose(c); } }
  fprintf(stderr,"[checkq] root F=%d M=%d |Q|=%ld dup=%ld records=%ld table=2^%d ender=%d range=[%ld,%ld)\n",F,M,nq,dup,nrec,bits,use_ender,start,end);
  int killer[L]; memset(killer,0,sizeof killer); time_t t0=time(0);
  FILE *elog=getenv("ENDERLOG")?fopen(getenv("ENDERLOG"),"ab"):NULL;  /* keys of ender children (for a later ender-free extension of Q) */
  for(long i=start;i<end;i++){ if(!fromkey(&list[i],X)){ printf("FAIL invalid key #%ld\n",i); return 1; }
    int t=frob(X); if(t<=1) continue;
    for(int a=t;a>=2;a--){ if(X[a]) continue; int ty=adjoin(X,t,a,Y); children++;
      if(ty<=1){ printf("FAIL #%ld move %d reaches the terminal P position\n",i,a); return 1; }
      int ok=0, kk=killer[a];
      if(kk>=2 && kk<=ty && !Y[kk]){ probes++; int tz=adjoin(Y,ty,kk,Z); if(tz<=1){ok=1;termw++;} else { Key kz; tokey(Z,&kz); if(tfind(&kz)) ok=1; } }
      for(int y=ty;y>=2 && !ok;y--){ if(Y[y]||y==kk) continue; probes++; int tz=adjoin(Y,ty,y,Z);
        if(tz<=1){ok=1;termw++;killer[a]=y;break;} Key kz; tokey(Z,&kz); if(tfind(&kz)){ok=1;killer[a]=y;} }
      if(!ok && use_ender && is_ender(Y)){ ok=1; enders++; if(elog){ Key ky; tokey(Y,&ky); fwrite(ky.k,1,15,elog); fputc(0,elog); } }
      if(!ok){ printf("FAIL #%ld move %d: child has no reply into Q%s\n",i,a,use_ender?"":" (ENDER=0)"); return 1; } }
    if(ck && (i+1)%ckstep==0){ char tmp[512]; snprintf(tmp,sizeof tmp,"%s.tmp",ck); FILE*c=fopen(tmp,"w"); if(!c) die("ckpt write");
      if(elog) fflush(elog); fprintf(c,"%ld %ld %ld %ld %ld %ld %ld\n",sz,nq,i+1,children,probes,termw,enders); fflush(c); fclose(c); rename(tmp,ck);
      fprintf(stderr,"[checkq] %ld/%ld keys children=%ld probes=%ld enders=%ld %lds\n",i+1,nq,children,probes,enders,(long)(time(0)-t0)); } }
  if(rstart!=0 || end!=nq){ printf("PARTIAL range [%ld,%ld) ok children=%ld probes=%ld enders=%ld (not a certificate)\n",start,end,children,probes,enders); return 3; }
  printf("OK root=[");for(int i=0;i<nroot;i++)printf("%s%d",i?",":"",root[i]); printf("] F=%d M=%d |Q|=%ld dup=%ld children=%ld probes=%ld terminal_w=%ld enders=%ld => root is P%s\n",F,M,nq,dup,children,probes,termw,enders,enders?" (uses the ender theorem)":" (no ender theorem used)");
  return 0; }
